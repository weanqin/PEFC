"""Graph utilities for EEG channel structure priors.

Builds a spatial adjacency / normalized graph-Laplacian from an electrode
montage. The structural prior is the per-dataset geometry artifact:

  - MODMA ``geometry.pt``        — GSN-HydroCel-129 (128 ch).
  - EDRA  ``geometry_edra.pt``   — standard 10-20 (62 ch, generated by
    ``scripts/build_edra_geometry.py``).

This is the ONLY real structural prior in the project (see prd.md
"structure-prior audit" of task 06-29-channel-selectivity-rootcause).

Used by:
  - R2 ``GraphChannelMixer`` (medium graph-prior injection) — replaces the dense
    ``input_proj`` so channel mixing is geometry-conditioned.
  - R1 ``ComponentProbeSite`` graph-surgery condition (optional).

Shapes here are pure numpy/torch over the C channel axis; no batch / time.
The channel count is dataset-dependent (128 for MODMA, 62 for EDRA).
"""

from __future__ import annotations

from typing import Tuple

import torch

from latent_flow.config import GEOMETRY_PATH, EDRA_GEOMETRY_PATH


# ---------------------------------------------------------------------------
# Geometry loading
# ---------------------------------------------------------------------------


def load_geometry(path=None, dataset="modma") -> Tuple[torch.Tensor, list]:
    """Load an electrode montage.

    Parameters
    ----------
    path : str or Path, optional
        Explicit path to a ``.pt`` geometry artifact. Takes precedence over
        ``dataset``.
    dataset : str, default "modma"
        Dataset key selecting the default geometry artifact: "modma" ->
        ``config.GEOMETRY_PATH`` (128 ch GSN), "edra" ->
        ``config.EDRA_GEOMETRY_PATH`` (62 ch 10-20).

    Returns
    -------
    coords : Tensor (C, 3) float32  — electrode 3D positions (metres).
    channel_names : list[str]       — index i <-> channel i.
    """
    if path is not None:
        p = str(path)
    elif dataset == "edra":
        p = str(EDRA_GEOMETRY_PATH)
    else:
        p = str(GEOMETRY_PATH)
    d = torch.load(p, weights_only=False)
    coords = d["coords"].float()
    names = list(d["channel_names"])
    assert coords.shape[0] == len(names), "coords / names length mismatch"
    return coords, names


# ---------------------------------------------------------------------------
# Adjacency construction
# ---------------------------------------------------------------------------


def pairwise_distance(coords: torch.Tensor) -> torch.Tensor:
    """Euclidean distance matrix (C, C). Diagonal is 0."""
    return torch.cdist(coords, coords, p=2)


def build_adjacency(coords: torch.Tensor, kernel: str = "gaussian",
                    sigma_d: float | None = None) -> torch.Tensor:
    """Spatial adjacency from electrode coordinates.

    Parameters
    ----------
    coords : (C, 3) electrode positions.
    kernel : "gaussian" -> A[a,b] = exp(-d^2 / (2 sigma_d^2));
             "binary"  -> A[a,b] = 1 if d <= sigma_d else 0 (sigma_d = threshold).
    sigma_d : kernel bandwidth / threshold. If None, the median pairwise distance
              is used (data-driven, avoids hand-tuning).

    Returns
    -------
    A : (C, C) float32, non-negative, symmetric, A[a,a] = 1 (self-loop kept).
    """
    coords = coords.float()
    d = pairwise_distance(coords)                       # (C, C)
    if sigma_d is None:
        sigma_d = float(d[d > 0].median().item())       # exclude the 0 diagonal
    if kernel == "gaussian":
        A = torch.exp(-(d ** 2) / (2.0 * sigma_d ** 2))
    elif kernel == "binary":
        A = (d <= sigma_d).float()
    else:
        raise ValueError(f"unknown kernel {kernel!r}")
    A = A.float()
    A = (A + A.t()) * 0.5                                # enforce symmetry
    A.fill_diagonal_(1.0)                                # keep self-loop
    return A


def normalize_adj(A: torch.Tensor, add_self_loops: bool = True) -> torch.Tensor:
    """Symmetric normalized adjacency A_hat = D^{-1/2} (A + I) D^{-1/2}.

    The standard graph-convolution normalization (Kipf & Welling). Adding self
    loops is on by default so each node retains its own feature.

    Properties: symmetric; each row sum <= 1; finite.
    """
    A = A.float()
    if add_self_loops:
        A = A + torch.eye(A.shape[0], dtype=A.dtype, device=A.device)
    deg = A.sum(dim=1).clamp_min(1e-12)
    d_inv_sqrt = deg.pow(-0.5)
    A_hat = d_inv_sqrt.unsqueeze(1) * A * d_inv_sqrt.unsqueeze(0)
    return A_hat


def build_normalized_adj(coords: torch.Tensor = None, kernel: str = "gaussian",
                         sigma_d: float | None = None,
                         add_self_loops: bool = True) -> torch.Tensor:
    """One-shot: coords -> normalized adjacency A_hat (C, C)."""
    if coords is None:
        coords, _ = load_geometry()
    A = build_adjacency(coords, kernel=kernel, sigma_d=sigma_d)
    return normalize_adj(A, add_self_loops=add_self_loops)


def mexican_hat(d: torch.Tensor, sigma: float) -> torch.Tensor:
    """Mexican hat (Ricker) wavelet kernel: band-pass, center-surround.

        w(d) = (1 - d^2 / sigma^2) * exp(-d^2 / (2 sigma^2))

    Properties (verified on the GSN-128 montage, sigma = median distance):
      - w(0) = 1 (self excitation)
      - positive for d < sigma (nearby excitation)
      - negative for d > sigma (lateral inhibition / surround suppression)
      - row-sum CV ~ 63% (vs Gaussian's 5.6%) => does NOT isotropize
    This is the band-pass counterpart to the low-pass Gaussian kernel; it
    preserves high-frequency channel structure instead of averaging it away.
    """
    s2 = float(sigma) ** 2
    return (1.0 - d ** 2 / s2) * torch.exp(-d ** 2 / (2.0 * s2))


def build_mexhat_adj(coords: torch.Tensor, sigma_d: float | None = None) -> torch.Tensor:
    """Raw (unnormalized) Mexican-hat adjacency from electrode coordinates.

    Returns (C, C) symmetric, with diagonal = 1 (self-excitation at d=0).
    Unlike the Gaussian adjacency, this is NOT normalized (Mexican hat's
    sign-changing weights break the D^{-1/2} normalization rationale); the
    mixer applies it directly as a band-pass operator.
    """
    coords = coords.float()
    d = pairwise_distance(coords)
    if sigma_d is None:
        sigma_d = float(d[d > 0].median().item())
    A = mexican_hat(d, sigma_d)
    A = (A + A.t()) * 0.5
    A.fill_diagonal_(1.0)
    return A.float()
